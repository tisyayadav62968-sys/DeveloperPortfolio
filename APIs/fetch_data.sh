#!/bin/bash
# Author: Tisya (2601730474)
# Description: Fetches GitHub profile and public API metrics using curl and jq

USERNAME="tisyayadav62968-sys"
USER_JSON=$(curl -s "https://api.github.com/users/$USERNAME")
REPOS_JSON=$(curl -s "https://api.github.com/users/$USERNAME/repos")
POSTS_JSON=$(curl -s "https://jsonplaceholder.typicode.com/posts?_limit=5")

LOGIN=$(echo "$USER_JSON" | jq -r '.login')
PUBLIC_REPOS=$(echo "$USER_JSON" | jq -r '.public_repos')
CREATED_AT=$(echo "$USER_JSON" | jq -r '.created_at')

cat << REPORT > APIs/api_report.md
# REST API Data Extraction Report

**Generated By:** Tisya (Roll No: 2601730474)  
**Date:** $(date)  

## 1. GitHub Account Overview
* **Username:** \`$LOGIN\`
* **Public Repositories:** $PUBLIC_REPOS
* **Account Created:** $CREATED_AT

## 2. Repository Details
| Repository Name | Primary Language | Stars | URL |
| :--- | :--- | :--- | :--- |
$(echo "$REPOS_JSON" | jq -r '.[] | "| \(.name) | \(.language // "Markdown/Shell") | \(.stargazers_count) | \(.html_url) |"')

## 3. Sample JSONPlaceholder API Records (\`GET /posts?_limit=5\`)
| Post ID | Title |
| :--- | :--- |
$(echo "$POSTS_JSON" | jq -r '.[] | "| \(.id) | \(.title) |"')
REPORT

echo "Report saved to APIs/api_report.md"
